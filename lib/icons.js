// ── THE TWO FACES ────────────────────────────────────
// An icon is a coin: the FIGURE side (a drawing of the thing) and the WORD side
// (the word itself, spelt in wedges). Both are optional and both are authored in
// the creator. Only one drawn → that one is what you get, whichever face was
// asked for; both drawn → the caller picks, per case, by passing `face`. There
// is deliberately no rule about which face belongs where: the call site decides.
export const FACES = ["figure", "word"]
export const faceOf = it => (it && it.face === "word" ? "word" : "figure") // stored entries default to figure
export const faceKey = (name, face) => (face === "word" ? `${name}:word` : name)
// a design counts as DRAWN once it has any mark at all
export const hasArt = d => !!d && ((d.fill && d.fill.length > 0) || (d.lines && d.lines.length > 0))

// the creator's saved designs live here; an entry whose name+face matches a
// built-in overrides it. Lazily loaded + cached; reloadIconOverrides() refreshes
// it (call after the creator saves so the game adopts the edit).
const ICON_STORE = "anon&mato:icons"
let overrides = null
function loadOverrides() {
  overrides = {}
  try {
    for (const it of JSON.parse(localStorage.getItem(ICON_STORE)) || []) overrides[faceKey(it.name, faceOf(it))] = it
  } catch {}
}
export function reloadIconOverrides() {
  loadOverrides()
}
// the design to paint for one side of one icon: the asked-for face if it's been
// drawn, else the OTHER face (a one-sided coin still reads), else the blank —
// which is what tells a painter to fall back to its built-in line art.
function wedgeDesign(name, face = "figure") {
  if (!overrides) loadOverrides()
  // the creator's save wins over the built-in, per side (built-in words are
  // keyed "name:word" in WEDGE_ICONS — see faceKey)
  const side = f => overrides[faceKey(name, f)] || WEDGE_ICONS[faceKey(name, f)] || null
  const want = side(face)
  if (hasArt(want)) return want
  const other = side(face === "word" ? "figure" : "word")
  return hasArt(other) ? other : want || BLANK
}
const BLANK = { n: 8, fill: [], lines: [] } // the empty canvas — "nothing drawn on this side"
// A painter for an icon that CAN be authored: it draws the wedge design as soon
// as either face has one, and falls back to the built-in line art (if any) while
// both canvases are still empty. Every icon in the game goes through here, so
// every one of them shows up in the creator ready to be drawn.
const authored = (name, fallback) => (ctx, x, y, r, face) => {
  const d = wedgeDesign(name, face)
  if (hasArt(d)) return drawWedges(ctx, d, x, y, r)
  if (fallback) fallback(ctx, x, y, r)
}

