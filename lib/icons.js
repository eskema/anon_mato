// `face` picks the coin's side — "figure" (the default, and what every call site
// asked for before faces existed) or "word". Ask for either freely: an icon that
// has only one side drawn gives you that one, so a call can prefer the word
// without having to know whether it's been drawn yet.
export function drawIcon(ctx, name, x, y, r, color, alpha = 1, face = "figure") {
  const fn = ICONS[name]
  if (!fn) return
  ctx.save()
  ctx.strokeStyle = color
  ctx.fillStyle = color
  ctx.globalAlpha = alpha
  fn(ctx, x, y, r, face)
  ctx.restore()
}
