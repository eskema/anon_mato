// the creator's saved designs live here; an entry whose name matches a built-in
// overrides it. Lazily loaded + cached; reloadIconOverrides() refreshes it (call
// after the creator saves so the game adopts the edit).
const ICON_STORE = "anon&mato:icons"
let overrides = null
function loadOverrides() {
  overrides = {}
  try {
    for (const it of JSON.parse(localStorage.getItem(ICON_STORE)) || []) overrides[it.name] = it
  } catch {}
}
export function reloadIconOverrides() {
  loadOverrides()
}
function wedgeDesign(name) {
  if (!overrides) loadOverrides()
  return overrides[name] || WEDGE_ICONS[name]
}

