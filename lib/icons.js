export function drawIcon(ctx, name, x, y, r, color, alpha = 1) {
  const fn = ICONS[name]
  if (!fn) return
  ctx.save()
  ctx.strokeStyle = color
  ctx.fillStyle = color
  ctx.globalAlpha = alpha
  fn(ctx, x, y, r)
  ctx.restore()
}
