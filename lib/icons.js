// The icon system — thin line-art glyphs for the radial menu (and the style
// guide). Each painter draws a symbol centred at (x,y) inside a box of radius
// r, using the caller's strokeStyle/fillStyle so it inherits the ink colour.
// Keep them simple: single-weight strokes, no fills except tiny accents —
// they read at badge size and match the game's hairline aesthetic.
//
// Naming is by MEANING, so the same glyph can serve several actions:
// verbs (rest, enter, home…), skills (scout, travel…), and structure
// (folder, back, dots). Add new symbols here; the menu references them by key.

const TAU = Math.PI * 2

// stroke setup: line width scales with the icon, round joins/caps
function pen(ctx, r, w = 0.14) {
  ctx.lineWidth = Math.max(1, r * w)
  ctx.lineJoin = "round"
  ctx.lineCap = "round"
}
const poly = (ctx, pts, close = true) => {
  ctx.beginPath()
  pts.forEach(([x, y], i) => (i ? ctx.lineTo(x, y) : ctx.moveTo(x, y)))
  if (close) ctx.closePath()
}
const dot = (ctx, x, y, rr) => {
  ctx.beginPath()
  ctx.arc(x, y, rr, 0, TAU)
  ctx.fill()
}

// ── wedge glyphs ─────────────────────────────────────
// Icons authored in the styles-page icon creator (lib/iconmaker.js): a pointy-
// top hex laid out as an iso cube's triangle lattice, stored as the list of
// filled wedges. Geometry mirrors iconmaker's (kept here so the game module has
// no DOM deps). A wedge id is "face:i:j:half" on an N×N-per-face lattice.
const W_SQ = Math.sqrt(3) / 2
const W_FACES = [
  [[-W_SQ, -0.5], [W_SQ, -0.5]], // top face
  [[-W_SQ, -0.5], [0, 1]], // left face
  [[W_SQ, -0.5], [0, 1]] // right face
]
function wedgeTri(id, N) {
  const [f, i, j, h] = id.split(":").map(Number)
  const [e1, e2] = W_FACES[f]
  const P = (a, b) => [(a / N) * e1[0] + (b / N) * e2[0], (a / N) * e1[1] + (b / N) * e2[1]]
  const p00 = P(i, j)
  const p11 = P(i + 1, j + 1)
  return h === 0 ? [p00, P(i + 1, j), p11] : [p00, p11, P(i, j + 1)]
}
// paint a wedge bitmap { n, fill, lines } centred at (x,y), the hex sized to r.
// The wedges tile (never overlap), so one filled path with the nonzero rule
// paints the whole glyph with no interior seams.
function drawWedges(ctx, data, x, y, r) {
  const s = r * 0.9 // hex radius — matches the `cube` glyph's footprint
  ctx.beginPath()
  for (const id of data.fill) {
    wedgeTri(id, data.n).forEach((p, k) => {
      const px = x + p[0] * s
      const py = y + p[1] * s
      k ? ctx.lineTo(px, py) : ctx.moveTo(px, py)
    })
    ctx.closePath()
  }
  ctx.fill()
  if (data.lines && data.lines.length) {
    pen(ctx, r)
    ctx.beginPath()
    for (const [ax, ay, bx, by] of data.lines) {
      ctx.moveTo(x + ax * s, y + ay * s)
      ctx.lineTo(x + bx * s, y + by * s)
    }
    ctx.stroke()
  }
}

